import { writeFileSync } from 'node:fs';

const SIZES = {
  small: { files: 5, linesPerFile: 40 },
  medium: { files: 25, linesPerFile: 60 },
  large: { files: 100, linesPerFile: 100 },
};

function hunk(newStart, lineCount) {
  const oldCount = Math.max(1, lineCount - 5);
  const out = [`@@ -1,${oldCount} +${newStart},${lineCount} @@`];
  for (let i = 0; i < lineCount; i++) {
    if (i % 4 === 3) out.push(`-  const old_${i} = compute(${i}, "left");`);
    else if (i % 3 === 1) out.push(`+  const next_${i} = compute(${i}, "right");`);
    else out.push(`   const ctx_${i} = baseline(${i}).withPad(" some context here ");`);
  }
  return out.join('\n');
}

const payload = {};
for (const [size, spec] of Object.entries(SIZES)) {
  const files = Array.from({ length: spec.files }, (_, f) => ({
    filename: `src/module-${f}/handler-${f % 7}.ts`,
    status: f % 5 === 0 ? 'modified' : 'modified',
    additions: Math.round(spec.linesPerFile / 2),
    deletions: Math.round(spec.linesPerFile / 6),
    changes: spec.linesPerFile,
    patch: hunk(1, spec.linesPerFile),
  }));
  payload[size] = JSON.stringify(files);
}

const ts = [
  '// Generated by make-fixtures.mjs — synthetic GitHub PR files payloads for CPU benchmarks.',
  '// Shape mirrors GET /repos/{owner}/{repo}/pulls/{pull_number}/files (one entry per file).',
  'export const PR_FILES: Record<\'small\' | \'medium\' | \'large\', string> = {',
  ...Object.entries(payload).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`),
  '};',
  '',
].join('\n');
writeFileSync(new URL('./pr-files.ts', import.meta.url), ts);
for (const [k, v] of Object.entries(payload)) {
  console.log(`${k}: ${v.length} bytes`);
}
